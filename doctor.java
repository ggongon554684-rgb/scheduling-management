    private void updatePatientQueue() {
   if (queuePanel == null) return;

    queuePanel.removeAll();
    String today = java.time.LocalDate.now().toString(); // yyyy-MM-dd
    java.util.List<String[]> todayPatients = new java.util.ArrayList<>();

    try (BufferedReader br = new BufferedReader(new FileReader("data.txt"))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] data = line.split(",");
            if (data.length >= 6) {
                String consultDateTime = data[4].trim(); // ✅ Date|Time at index 4
                String datePart = consultDateTime.split(" ")[0];
                String status = data[5].trim().toLowerCase(); // ✅ status at index 5

                if (datePart.equals(today) && 
                    (status.equals("scheduled") || status.equals("pending"))) {
                    todayPatients.add(data);
                }
            }
        }
    } catch (IOException e) {
        System.err.println("Error reading patient queue: " + e.getMessage());
    }

    // Sort by consultation time
    todayPatients.sort((a, b) -> {
        String timeA = a[4].substring(11); // ✅ use index 4
        String timeB = b[4].substring(11);
        return timeA.compareTo(timeB);
    });

    int count = Math.min(2, todayPatients.size());

    if (count == 0) {
        JLabel noPatients = new JLabel("No patients scheduled for today", SwingConstants.CENTER);
        noPatients.setFont(new Font("Segoe UI", Font.ITALIC, 14));
        noPatients.setForeground(Color.WHITE);
        noPatients.setAlignmentX(Component.CENTER_ALIGNMENT);
        queuePanel.add(Box.createVerticalGlue());
        queuePanel.add(noPatients);
        queuePanel.add(Box.createVerticalGlue());
    } else {
        for (int i = 0; i < count; i++) {
            String[] patient = todayPatients.get(i);
            JPanel card = createPatientCard(
                patient[0], // name
                patient[1], // age
                patient[2], // symptoms
                patient[4].substring(11) // ✅ show time part from Date|Time
            );
            queuePanel.add(card);
            if (i < count - 1) {
                queuePanel.add(Box.createRigidArea(new Dimension(0, 8)));
            }
        }
    }

    queuePanel.revalidate();
    queuePanel.repaint();
}

    private javax.swing.JPanel createPatientCard(String name, String age, String symptoms, String time) {
    javax.swing.JPanel card = new javax.swing.JPanel();
    card.setLayout(new BorderLayout(10, 5));
    card.setBackground(new Color(255, 255, 255, 255)); // Semi-transparent white
    card.setBorder(BorderFactory.createCompoundBorder(
        BorderFactory.createLineBorder(new Color(0, 82, 164), 2),
        BorderFactory.createEmptyBorder(8, 12, 8, 12)
    ));
    card.setMaximumSize(new Dimension(Integer.MAX_VALUE, 70));
    
    // Time label (left)
    JLabel timeLabel = new JLabel("🕐 " + time);
    timeLabel.setFont(new Font("Segoe UI", Font.BOLD, 14));
    timeLabel.setForeground(new Color(0, 102, 102));
    card.add(timeLabel, BorderLayout.WEST);
    
    // Patient info (center)
    javax.swing.JPanel infoPanel = new javax.swing.JPanel();
    infoPanel.setLayout(new BoxLayout(infoPanel, BoxLayout.Y_AXIS));
    infoPanel.setOpaque(false);
    
    JLabel nameLabel = new JLabel(name + " (" + age + ")");
    nameLabel.setFont(new Font("Segoe UI", Font.BOLD, 15));
    nameLabel.setForeground(Color.BLACK);
    
    JLabel symptomsLabel = new JLabel("Symptoms: " + symptoms);
    symptomsLabel.setFont(new Font("Segoe UI", Font.PLAIN, 12));
    symptomsLabel.setForeground(Color.DARK_GRAY);
    
    infoPanel.add(nameLabel);
    infoPanel.add(symptomsLabel);
    
    card.add(infoPanel, BorderLayout.CENTER);
    
    return card;
}
