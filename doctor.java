    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                     
    int selectedRow = jTable1.getSelectedRow();
    
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a patient first.");
        return;
    }
    
    String name = jTable1.getValueAt(selectedRow, 0).toString().trim();
    String age = jTable1.getValueAt(selectedRow, 1).toString().trim();
    String symptoms = jTable1.getValueAt(selectedRow, 2).toString().trim();
    String dateEntered = jTable1.getValueAt(selectedRow, 3).toString().trim();
    String consultationDate = jTable1.getValueAt(selectedRow, 4).toString().trim();
    
    File file = new File("data.txt");
    File tempFile = new File("data_temp.txt");
    boolean updated = false;
    
    try (BufferedReader reader = new BufferedReader(new FileReader(file));
         BufferedWriter writer = new BufferedWriter(new FileWriter(tempFile))) {
        
        String line;
        while ((line = reader.readLine()) != null) {
            String[] data = line.split(",");
            
            
            // Match by name AND dateEntered (data[4] is dateEntered in file)
            if (data.length >= 6 && 
                data[0].trim().equalsIgnoreCase(name) && 
                data[3].trim().equals(dateEntered)) {
                
                data[5] = "On-Going"; // Update status
                writer.write(String.join(",", data));
                updated = true;
                System.out.println("✅ Updated record: " + String.join(",", data));
            } else {
                writer.write(line);
            }
            writer.newLine();
        }
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error updating patient status: " + e.getMessage());
        return;
    }
    
    if (!updated) {
        System.err.println("⚠️ Patient not found in file: " + name + " | dateEntered: " + dateEntered);
        JOptionPane.showMessageDialog(this, "Patient record not found in file!");
        return;
    }
    
    // File replacement
    if (file.delete()) {
        if (tempFile.renameTo(file)) {
            System.out.println("✅ data.txt updated successfully.");
        } else {
            System.err.println("⚠️ Failed to rename temp file.");
        }
    } else {
        System.err.println("⚠️ Failed to delete original file.");
    }
    
    // Refresh doctor table after update
    refreshDoctorTable();
    updatePatientQueue();
    
    // Open diagnosticpad
    diagnosticpad diag = new diagnosticpad(name, age, symptoms, consultationDate, dateEntered, this);
    diag.setVisible(true);
    diag.setLocationRelativeTo(null);
    
    }//GEN-LAST:event_jButton2ActionPerformed

